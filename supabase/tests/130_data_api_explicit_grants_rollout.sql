-- Supabase 2026-10-30 Data API rollout: new public tables require explicit grants.
-- Test-only DDL is enclosed in a transaction and rolled back; no production migration.
-- https://supabase.com/changelog/45329-breaking-change-tables-not-exposed-to-data-and-graphql-api-automatically
begin;
create extension if not exists pgtap with schema extensions;
select plan(12);

-- Existing OnePick table access must survive the change to future defaults.
select ok(
  has_table_privilege('authenticated', 'public.item_photo_candidates', 'SELECT'),
  'existing item-photo candidates remain readable by authenticated users'
);
select ok(
  not has_table_privilege('anon', 'public.item_photo_candidates', 'SELECT'),
  'existing item-photo candidates remain hidden from anonymous users'
);

-- Reproduce the documented 2026-10-30 default-privilege change for the
-- postgres migration role, but only inside this rolled-back test transaction.
alter default privileges for role postgres in schema public
  revoke select, insert, update, delete on tables
  from anon, authenticated, service_role;
alter default privileges for role postgres in schema public
  revoke usage, select on sequences
  from anon, authenticated, service_role;

create table public.test_130_data_api_grants (
  id bigint generated by default as identity primary key,
  owner_id uuid not null
);
alter table public.test_130_data_api_grants enable row level security;

-- RLS alone does not grant table or sequence privileges.
select ok(
  not has_table_privilege('anon', 'public.test_130_data_api_grants', 'SELECT'),
  'a new public table is not automatically readable by anon'
);
select ok(
  not has_table_privilege('authenticated', 'public.test_130_data_api_grants', 'SELECT'),
  'a new public table is not automatically readable by authenticated'
);
select ok(
  not has_table_privilege('authenticated', 'public.test_130_data_api_grants', 'INSERT'),
  'a new public table is not automatically writable by authenticated'
);
select ok(
  not has_sequence_privilege(
    'authenticated',
    pg_get_serial_sequence('public.test_130_data_api_grants', 'id'),
    'USAGE'
  ),
  'the identity sequence also receives no implicit authenticated USAGE'
);
select ok(
  (select relrowsecurity from pg_class
   where oid = 'public.test_130_data_api_grants'::regclass),
  'RLS is enabled on the rollout test table'
);

-- Explicit opt-in for one operation and one role only.
grant select on public.test_130_data_api_grants to authenticated;
create policy test_130_owner_read on public.test_130_data_api_grants
  for select to authenticated using ((select auth.uid()) = owner_id);
insert into public.test_130_data_api_grants (owner_id)
values ('a1300000-0000-4000-8000-000000000001');

select ok(
  has_table_privilege('authenticated', 'public.test_130_data_api_grants', 'SELECT'),
  'authenticated SELECT becomes available only after explicit GRANT'
);
select ok(
  not has_table_privilege('anon', 'public.test_130_data_api_grants', 'SELECT'),
  'explicit authenticated SELECT does not open anonymous access'
);
select ok(
  not has_table_privilege('authenticated', 'public.test_130_data_api_grants', 'INSERT'),
  'explicit SELECT does not grant write access'
);

set local role authenticated;
select is(
  (select count(*)::integer from public.test_130_data_api_grants),
  0,
  'RLS still hides a row from an authenticated request without its owner identity'
);
select set_config(
  'request.jwt.claim.sub', 'a1300000-0000-4000-8000-000000000001', true
);
select is(
  (select count(*)::integer from public.test_130_data_api_grants),
  1,
  'a matching authenticated owner sees the row through explicit GRANT and RLS'
);
reset role;

select * from finish();
rollback;
